#!/usr/bin/env python3
"""Extract the data of Colossal Cave Adventure from the C source into Python.

This is a build-time tool: it reads the data headers of troglobit/adventure (the
BDS C to Unix port of Crowther and Woods) and writes adventure/data.py. Nothing is
typed in by hand: the text, the room and travel tables, the vocabulary and the
starting values of the game arrays all come from the C files.

Usage:  python tools/gen_adventure_data.py SRC_DIR [OUT_FILE]
        (SRC_DIR holds advcave.h, advword.h, advent1.h .. advent4.h and advent.c;
         OUT_FILE defaults to adventure/data.py next to this script's parent)
"""

import os
import re
import sys

HEADER = '''"""Data of Colossal Cave Adventure, extracted from the C source.

GENERATED by tools/gen_adventure_data.py -- do not edit by hand (see NOTICE).

Colossal Cave Adventure: Will Crowther (original, PDP-10, 1975-77) and Don Woods
(major features, 1977); conversion to BDS C by J. R. Jaeger (1981); UNIX
standardisation by Jerry D. Pohl (1990); port to QNX by James Lummel (1993); Linux
port and cleanup by Joachim Wiberg (troglobit/adventure), whose repository
dedicates the source to the public domain under the Unlicense. Its README adds
that the original authors' licence is unknown but widely taken to be public
domain. Full credits are in NOTICE.

ROOM_LONG, ROOM_SHORT, ITEM_TEXT and MESSAGES are the texts the game prints
(advent1.h .. advent4.h); TRAVEL is the travel table (advcave.h), VOCAB the
vocabulary in the order the game's binary search needs (advword.h); INIT_* and
ACTMSG are the starting values set in initplay() of advent.c.
"""

'''


def items(text):
    """The comma-separated items of a C initialiser as a list: a string (adjacent
    literals are joined, as C does) or None for NULL. Comments are skipped."""
    out, cur, null = [], None, False
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c in " \t\r\n":
            i += 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            i = text.index("*/", i) + 2
        elif c == '"':
            j = i + 1
            buf = []
            while text[j] != '"':
                if text[j] == "\\":
                    esc = text[j + 1]
                    if esc not in ESCAPES:
                        raise ValueError("unexpected escape \\" + esc)
                    buf.append(ESCAPES[esc])
                    j += 2
                else:
                    buf.append(text[j])
                    j += 1
            cur = (cur or "") + "".join(buf)
            i = j + 1
        elif c == ",":
            out.append(cur)
            cur = None
            i += 1
        elif text.startswith("NULL", i):
            null = True
            i += 4
        else:
            raise ValueError("unexpected %r near %r" % (c, text[i:i + 30]))
    if cur is not None or null:
        out.append(cur)
    return out


ESCAPES = {"n": "\n", '"': '"', "\\": "\\"}


def c_array(text, name):
    """"name[...] = { ... };" as a list of strings (None for NULL)."""
    m = re.search(r"\b%s\s*\[[^\]]*\]\s*=\s*\{" % re.escape(name), text)
    if not m:
        raise ValueError("array %s not found" % name)
    return items(text[m.end():text.index("};", m.end())])


def read(src, name):
    with open(os.path.join(src, name), encoding="latin-1", newline="") as fh:
        return fh.read().replace("\r\n", "\n")


def vocab(text):
    m = re.search(r"struct wac wc\[\]\s*=\s*\{", text)
    body = text[m.end():text.index("};", m.end())]
    words = re.findall(r'\{\s*"([^"]*)"\s*,\s*(\d+)\s*\}', body)
    return [(w, int(c)) for w, c in words]


def scan_ints(text, array):
    """advent.c: scanint(&array[k], "a,b,c,") calls -> {index: value}."""
    out = {}
    pat = re.compile(r'scanint\(\s*(?:&\s*)?%s\s*(?:\[\s*(\d+)\s*\])?\s*,\s*"([^"]*)"\s*\)' % array)
    for m in pat.finditer(text):
        start = int(m.group(1) or 0)
        for k, v in enumerate(x for x in m.group(2).split(",") if x != ""):
            out[start + k] = int(v)
    return out


def fmt_list(name, items, comment=""):
    lines = ["%s = [%s" % (name, "  # " + comment if comment else "")]
    for k, it in enumerate(items):
        lines.append("    %r,  # %d" % (it, k + 1))
    lines.append("]\n")
    return "\n".join(lines)


def fmt_dense(name, mapping, size, comment=""):
    vals = [mapping.get(i, 0) for i in range(size)]
    rows = []
    for i in range(0, size, 12):
        rows.append("    " + ", ".join(str(v) for v in vals[i:i + 12]) + ",")
    return "%s = [%s\n%s\n]\n" % (name, "  # " + comment if comment else "", "\n".join(rows))


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    src = argv[1]
    out = argv[2] if len(argv) > 2 else os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "adventure", "data.py")
    t1, t2, t3, t4 = (read(src, "advent%d.h" % i) for i in range(1, 5))
    cave_h, word_h, advent_c, advent_h = (read(src, n) for n in
                                          ("advcave.h", "advword.h", "advent.c", "advent.h"))
    long_ = c_array(t1, "adventtxt1")
    short = c_array(t2, "adventtxt2")
    objs = c_array(t3, "adventtxt3")
    msgs = c_array(t4, "adventtxt4")
    cave = c_array(cave_h, "cave")
    words = vocab(word_h)
    consts = {k: int(v) for k, v in re.findall(r"^#define\s+(\w+)\s+(\d+)\b", advent_h, re.M)}
    assert len(long_) == len(short) == len(cave) == consts["MAXLOC"], (len(long_), len(short),
                                                                         len(cave))
    assert len(msgs) == consts["MAXMSG"], len(msgs)
    assert len(words) == consts["MAXWC"], len(words)
    assert len(objs) == 64, len(objs)

    parts = [HEADER, "# advent.h: sizes, and the numbers of objects, verbs and so on\n"
             + "".join("%s = %d\n" % kv for kv in consts.items())]
    parts.append(fmt_list("ROOM_LONG", long_, "advent1.h: long descriptions, room 1.."))
    parts.append(fmt_list("ROOM_SHORT", short, "advent2.h: short descriptions"))
    parts.append(fmt_list("ITEM_TEXT", objs,
                          "advent3.h: object texts '/name/state0/state1/', None = no text"))
    parts.append(fmt_list("MESSAGES", msgs, "advent4.h: numbered messages (rspeak)"))
    parts.append(fmt_list("TRAVEL", cave, "advcave.h: travel table, dest*1000000+verb*1000+cond"))
    parts.append("VOCAB = [  # advword.h: (word, code), in the table's own order\n"
                 + "".join("    (%r, %d),\n" % wc for wc in words) + "]\n")
    parts.append(fmt_dense("INIT_COND", scan_ints(advent_c, "cond"), consts["MAXLOC"],
                           "initplay(): location status bits"))
    parts.append(fmt_dense("INIT_PLACE", scan_ints(advent_c, "place"), consts["MAXOBJ"],
                           "initplay(): where each object starts"))
    parts.append(fmt_dense("INIT_FIXED", scan_ints(advent_c, "fixed"), consts["MAXOBJ"],
                           "initplay(): second location of two-place objects"))
    parts.append(fmt_dense("ACTMSG", scan_ints(advent_c, "actmsg"), 32,
                           "initplay(): default message per verb"))
    parts.append("INIT_DLOC = %r  # initplay(): dwarf start locations\n"
                 % [scan_ints(advent_c, "dloc")[i] for i in range(7)])
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(parts))
    print("wrote %s (%d rooms, %d messages, %d words)" % (out, len(long_), len(msgs), len(words)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
